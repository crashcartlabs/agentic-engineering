    print(f"launcher: {launcher} ({'installed' if launcher.is_file() else 'missing'})")
    if not launcher.is_file():
        print("hint: run `agentic setup` (or `python3 scripts/toolbelt.py install`) to install the launcher")
    print("capability: core workflow = all platforms")
    print("capability: dashboard watcher = macOS/Linux")
    print("capability: cmux fleet = macOS only")
    print("capability: disposable sandbox = Docker hosts")
    for command in ("claude", "codex", "pi", "docker"):
        status, _ = command_version(command)
        if status != "available":
            print(f"hint: {CAPABILITY_HINTS[command]}")
    cmux_status, _ = command_version("cmux")
    if cmux_status != "available":
        print(f"hint: {cmux_hint()}")
