REPO = pathlib.Path(__file__).resolve().parents[1]
MANIFEST_PATH = REPO / "toolbelt.json"
MANAGED_MARKER = ".agentic-engineering-managed.json"
INSTALL_STATE_RELATIVE = pathlib.Path(".agentic-engineering") / "install-state.json"
GENERATED_HEADER = "# Generated by Agentic Engineering. Do not edit by hand."
PROVIDERS = ("claude", "codex", "pi", "hermes")
# Hermes ships its own bundled skills under these names (plan, tdd, dogfood) or
# owns the namespace as a category directory (research); installing the toolbelt's
# would shadow or collide. The agentic-engineering router skill covers them from
# the repo.
HERMES_EXCLUDED = frozenset({"plan", "tdd", "dogfood", "research"})
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
# Official SemVer 2.0.0 shape (semver.org), mirroring the release publisher:
# ASCII + fullmatch, because `$` accepts a trailing newline and a bare `\d`
# accepts non-ASCII digits.
SEMVER_RE = re.compile(
    r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)"
    r"(?:-(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*)?"
    r"(?:\+[0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*)?",
    re.ASCII,
)
MAX_SCAFFOLD_BYTES = 1024 * 1024


class ToolbeltError(RuntimeError):
    """An expected, user-actionable toolbelt failure."""


def load_manifest() -> dict[str, object]:
    try:
        return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ToolbeltError(f"cannot read {MANIFEST_PATH}: {exc}") from exc


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _decode_scalar(value: str) -> str:
    """Decode a frontmatter scalar to its real string value. Double-quoted
    values are JSON strings, so escapes (``\\"``, ``\\uXXXX``) are resolved
    rather than passed through verbatim — otherwise re-encoding them for a
    provider adapter double-escapes the quotes and turns em-dashes into
    ``\\u2014``. Other quoted values just have their surrounding quotes stripped."""
    if value[:1] == '"':
        try:
            return json.loads(value)
        except json.JSONDecodeError:
            pass
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_frontmatter(path: pathlib.Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ToolbeltError(f"{path}: missing YAML frontmatter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ToolbeltError(f"{path}: unterminated YAML frontmatter")
    fields: dict[str, str] = {}
    for line in text[4:end].splitlines():
        match = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if match:
            fields[match.group(1)] = _decode_scalar(match.group(2).strip())
    return fields, text[end + 5 :]


def skill_dirs() -> list[pathlib.Path]:
    root = REPO / "skills"
    if not root.is_dir():
        raise ToolbeltError(f"canonical skills directory is missing: {root}")
    return sorted(path for path in root.iterdir() if path.is_dir() and (path / "SKILL.md").is_file())


def hermes_skill_dirs() -> list[pathlib.Path]:
    """Skills installed into Hermes: all canonical skills minus HERMES_EXCLUDED."""
    return [source for source in skill_dirs() if source.name not in HERMES_EXCLUDED]


def hermes_skills_root(home: pathlib.Path) -> pathlib.Path:
    """Hermes skills root: $HERMES_HOME/skills when set, else ~/.hermes/skills.

    Always absolute: a relative HERMES_HOME would change meaning with the process
    CWD and corrupt artifact records (relative records vs absolute validation).
    """
    env = os.environ.get("HERMES_HOME")
    if env:
        return pathlib.Path(os.path.abspath(os.path.expanduser(env))) / "skills"
    return pathlib.Path(os.path.abspath(home.expanduser())) / ".hermes" / "skills"


def render_codex_agent(source: pathlib.Path) -> str:
    fields, body = parse_frontmatter(source)
    for required in ("name", "description"):
        if not fields.get(required):
            raise ToolbeltError(f"{source}: missing {required!r}")
    if "'''" in body:
        raise ToolbeltError(f"{source}: prompt contains unsupported TOML literal delimiter")
    return (
        f"{GENERATED_HEADER}\n"
        f"name = {json.dumps(fields['name'], ensure_ascii=False)}\n"
        f"description = {json.dumps(fields['description'], ensure_ascii=False)}\n"
        "developer_instructions = '''\n"
        f"{body.rstrip()}\n"
        "'''\n"
    )


def generated_codex_agents() -> dict[pathlib.Path, str]:
    output: dict[pathlib.Path, str] = {}
    for source in sorted((REPO / "agents").glob("*.md")):
        fields, _ = parse_frontmatter(source)
        name = fields.get("name")
        if not name:
            raise ToolbeltError(f"{source}: missing agent name")
        if not NAME_RE.fullmatch(name):
            raise ToolbeltError(f"{source}: unsafe agent name {name!r}")
        output[REPO / "providers" / "codex" / "agents" / f"{name}.toml"] = render_codex_agent(source)
    return output


def render_claude_skill(source: pathlib.Path) -> str:
    fields, body = parse_frontmatter(source)
    name = fields.get("name", "")
    description = fields.get("description", "")
    if not name or not description:
        raise ToolbeltError(f"{source}: missing name or description")
    policy = load_manifest().get("skillPolicy", {})
    explicit = set(policy.get("explicit", [])) if isinstance(policy, dict) else set()
    arguments = policy.get("arguments", {}) if isinstance(policy, dict) else {}
    lines = ["---", f"name: {name}", f"description: {json.dumps(description, ensure_ascii=False)}"]
    if name in explicit:
        lines.append("disable-model-invocation: true")
    if isinstance(arguments, dict) and isinstance(arguments.get(name), str):
        lines.append(f"argument-hint: {json.dumps(arguments[name], ensure_ascii=False)}")
    lines.extend(["---", "", body.rstrip(), ""])
    return "\n".join(lines)


def generated_claude_skills() -> dict[pathlib.Path, bytes]:
    output: dict[pathlib.Path, bytes] = {}
    destination_root = REPO / "providers" / "claude" / "skills"
    for directory in skill_dirs():
        for source in sorted(path for path in directory.rglob("*") if path.is_file()):
            relative = source.relative_to(directory)
            destination = destination_root / directory.name / relative
            if relative == pathlib.Path("SKILL.md"):
                output[destination] = render_claude_skill(source).encode("utf-8")
            else:
                output[destination] = source.read_bytes()
    return output


def generated_provider_files() -> dict[pathlib.Path, bytes]:
    output = generated_claude_skills()
    output.update(
        {path: content.encode("utf-8") for path, content in generated_codex_agents().items()}
    )
    return output


def validate_source(*, check_generated: bool = True) -> list[str]:
    errors: list[str] = []
    # A malformed or non-object primary manifest is a repository finding (gate
    # exit 1), never a broken-tool crash: parse it defensively before use.
    try:
        manifest: object = load_manifest()
    except ToolbeltError as exc:
        errors.append(str(exc))
        manifest = {}
    if not isinstance(manifest, dict):
        errors.append(f"{MANIFEST_PATH}: manifest root must be a JSON object")
        manifest = {}
    names: set[str] = set()
    allowed_frontmatter = {"name", "description"}
    for directory in skill_dirs():
        fields, _ = parse_frontmatter(directory / "SKILL.md")
        name = fields.get("name", "")
        names.add(name)
        if name != directory.name:
            errors.append(f"{directory}: skill name {name!r} does not match directory")
        if not fields.get("description"):
            errors.append(f"{directory}: missing description")
        extras = sorted(set(fields) - allowed_frontmatter)
        if extras:
            errors.append(f"{directory}: provider-specific frontmatter: {', '.join(extras)}")
        if not (directory / "tests.md").is_file():
            errors.append(f"{directory}: missing tests.md")

    workflow = manifest.get("workflow", [])
    if isinstance(workflow, list):
        for phase in workflow:
            if not isinstance(phase, dict):
                errors.append("toolbelt.json: workflow phase must be an object")
                continue
            for name in phase.get("skills", []):
                if name not in names:
                    errors.append(f"toolbelt.json: workflow references unknown skill {name!r}")

    if check_generated:
        expected_files = generated_provider_files()
        for path, expected in expected_files.items():
            actual = path.read_bytes() if path.is_file() else None
            if actual != expected:
                errors.append(f"{path}: generated provider adapter is missing or stale")
        for root in (REPO / "providers" / "claude" / "skills", REPO / "providers" / "codex" / "agents"):
            if root.is_dir():
                extras = sorted(path for path in root.rglob("*") if path.is_file() and path not in expected_files)
                for path in extras:
                    errors.append(f"{path}: stale generated provider file")

    manifest_versions: dict[str, object] = {}
    for rel in ("toolbelt.json", "package.json", ".claude-plugin/plugin.json", ".codex-plugin/plugin.json"):
        path = REPO / rel
        if not path.is_file():
            errors.append(f"{rel}: release manifest is missing")
            continue
        try:
            manifest = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            errors.append(f"{rel}: invalid JSON")
            continue
        if not isinstance(manifest, dict):
            errors.append(f"{rel}: manifest root must be a JSON object")
            continue
        version = manifest.get("version")
        # Every manifest must carry the release identity; a missing version must
        # fail rather than being filtered out of the comparison.
        if not isinstance(version, str) or not version.strip():
            errors.append(f"{rel}: missing or empty `version`")
            continue
        manifest_versions[rel] = version
    if len(set(manifest_versions.values())) > 1:
        errors.append(f"manifest version mismatch: {manifest_versions}")
    elif manifest_versions:
        # The changelog is public consumers' only cross-release diff
        # (docs/publishing.md), so a synchronized version without an entry must
        # not be publishable.
        release = next(iter(manifest_versions.values()))
        if not SEMVER_RE.fullmatch(release):
            # Same contract the publisher enforces at preflight: pre-commit must
            # refuse what publishing would refuse, not advertise "valid" for it.
            errors.append(f"synchronized version {release!r} is not valid SemVer")
        changelog = REPO / "CHANGELOG.md"
        if not changelog.is_file():
            errors.append("CHANGELOG.md is missing")
        elif not changelog_has_release_heading(changelog.read_text(encoding="utf-8"), release):
            errors.append(f"CHANGELOG.md has no heading for version {release}")
    return errors


def changelog_has_release_heading(text: str, release: str) -> bool:
    """A line-anchored `## [<release>]` heading in the *rendered* changelog.

    A matching line inside a fenced code block is a documented example, not the
    release entry — the same distinction the plan lint draws — so fenced content
    is excluded before matching. Mirrored by the release publisher's preflight.
    """
    heading = re.compile(rf"^## \[{re.escape(release)}\]")
    fence: tuple[str, int] | None = None
    for line in text.splitlines():
        match = re.match(r" {0,3}(`{3,}|~{3,})", line)
        if match:
            marker = match.group(1)
            if fence is None:
                fence = (marker[0], len(marker))
            elif marker[0] == fence[0] and len(marker) >= fence[1] and line.strip() == marker:
                fence = None
            continue
        if fence is None and heading.match(line):
            return True
    return False


def generate(*, check: bool) -> int:
    expected = generated_provider_files()
    generated_roots = (
        REPO / "providers" / "claude" / "skills",
        REPO / "providers" / "codex" / "agents",
    )
    actual = {
        path
        for root in generated_roots
        if root.is_dir()
        for path in root.rglob("*")
        if path.is_file()
    }
    stale = [path for path, content in expected.items() if not path.is_file() or path.read_bytes() != content]
    stale.extend(sorted(actual - set(expected)))
    if stale and not check:
        for root in generated_roots:
            if root.exists():
                shutil.rmtree(root)
        for path, content in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(f"generated {path.relative_to(REPO)}")
    if check and stale:
        for path in sorted(set(stale)):
            print(f"stale generated file: {path.relative_to(REPO)}")
        return 1
    if not stale:
        print("provider adapters: current")
    return 0


def marker_payload(source: pathlib.Path) -> dict[str, object]:
    manifest = load_manifest()
    return {
        "name": manifest["name"],
        "schemaVersion": 2,
        "source": str(source),
        "version": manifest["version"],
    }


def managed_dir_snapshot(path: pathlib.Path) -> dict[str, str]:
    return {
        candidate.relative_to(path).as_posix(): sha256(candidate)
        for candidate in sorted(path.rglob("*"))
        if candidate.is_file() and candidate.name != MANAGED_MARKER
    }


def managed_dir_marker(path: pathlib.Path) -> dict[str, object] | None:
    marker = path / MANAGED_MARKER
    if not marker.is_file():
        return None
    try:
        data = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if data.get("name") == "agentic-engineering" else None


def is_managed_dir(path: pathlib.Path) -> bool:
    return managed_dir_marker(path) is not None


def require_pristine_managed_dir(path: pathlib.Path) -> None:
    marker = managed_dir_marker(path)
    if marker is None:
        raise ToolbeltError(f"refusing to replace unmanaged directory: {path}")
    expected = marker.get("files")
    if not isinstance(expected, dict):
        raise ToolbeltError(
            f"managed directory has no content inventory: {path}; rerun with --force once"
        )
    actual = managed_dir_snapshot(path)
    if actual != expected:
        raise ToolbeltError(f"managed directory was edited since installation: {path}")


def copy_managed_dir(
    source: pathlib.Path,
    destination: pathlib.Path,
    *,
    force: bool,
    dry_run: bool,
    extra_files: dict[str, str] | None = None,
) -> None:
    """Copy a managed directory, optionally injecting extra files.

    ``extra_files`` maps a relative path to content; the files are written into the
    candidate before the managed marker is snapshotted, so the inventory and the
    directory always agree (re-install pristine checks stay green).
    """
    destination_exists = destination.exists() or destination.is_symlink()
    if destination_exists and not force:
        require_pristine_managed_dir(destination)
    action = "update" if destination_exists else "install"
    print(f"{action}: {destination}")
    if dry_run:
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    temp_root = pathlib.Path(
        tempfile.mkdtemp(prefix=f".{destination.name}.agentic-", dir=destination.parent)
    )
    candidate = temp_root / "candidate"
    backup = temp_root / "previous"
    moved_previous = False
    try:
        shutil.copytree(source, candidate)
        if extra_files:
            for relative, content in extra_files.items():
                target = candidate / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
        marker = {**marker_payload(source), "files": managed_dir_snapshot(candidate)}
        (candidate / MANAGED_MARKER).write_text(
            json.dumps(marker, indent=2) + "\n", encoding="utf-8"
        )
        if destination_exists:
            os.replace(destination, backup)
            moved_previous = True
        try:
            os.replace(candidate, destination)
        except BaseException:
            if moved_previous and not destination.exists():
                os.replace(backup, destination)
            raise
        if moved_previous:
            if backup.is_dir() and not backup.is_symlink():
                shutil.rmtree(backup)
            else:
                backup.unlink(missing_ok=True)
    finally:
        shutil.rmtree(temp_root, ignore_errors=True)


def managed_sidecar(path: pathlib.Path) -> pathlib.Path:
    return path.with_name(f".{path.name}.agentic-engineering.json")


def write_managed_file(
    path: pathlib.Path,
    content: str,
    *,
    force: bool,
    dry_run: bool,
    executable: bool = False,
) -> None:
    sidecar = managed_sidecar(path)
    if path.exists() and not force:
        if not sidecar.is_file():
            raise ToolbeltError(f"refusing to replace unmanaged file: {path}")
        try:
            prior = json.loads(sidecar.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ToolbeltError(f"invalid managed-file marker: {sidecar}") from exc
        if prior.get("sha256") != sha256(path):
            raise ToolbeltError(f"managed file was edited since installation: {path}")
    action = "update" if path.exists() else "install"
    print(f"{action}: {path}")
    if dry_run:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    if executable and os.name != "nt":
        path.chmod(path.stat().st_mode | 0o755)
    sidecar.write_text(
        json.dumps({**marker_payload(REPO), "sha256": sha256(path)}, indent=2) + "\n",
        encoding="utf-8",
    )


def launcher_path(home: pathlib.Path) -> pathlib.Path:
    if os.name == "nt":
        return home / "AppData" / "Local" / "AgenticEngineering" / "bin" / "agentic.cmd"
    return home / ".local" / "bin" / "agentic"


def launcher_content() -> str:
    script = REPO / "scripts" / "toolbelt.py"
    if os.name == "nt":
        return f'@py -3 "{script}" %*\r\n'
    return f'#!/bin/sh\nexec python3 {shlex.quote(str(script))} "$@"\n'


def parse_providers(value: str) -> tuple[str, ...]:
    if value == "all":
        return PROVIDERS
    requested = tuple(part.strip() for part in value.split(",") if part.strip())
    unknown = sorted(set(requested) - set(PROVIDERS))
    if unknown:
        raise ToolbeltError(f"unknown provider(s): {', '.join(unknown)}")
    return requested


def install_state_path(home: pathlib.Path) -> pathlib.Path:
    return home.expanduser() / INSTALL_STATE_RELATIVE


def artifact(kind: str, path: pathlib.Path) -> dict[str, str]:
    return {"kind": kind, "path": str(path)}


def desired_artifacts(home: pathlib.Path, group: str) -> list[dict[str, str]]:
    if group == "shared":
        return [artifact("dir", home / ".agents" / "skills" / source.name) for source in skill_dirs()]
    if group == "claude":
        skill_root = REPO / "providers" / "claude" / "skills"
        records = [
            artifact("dir", home / ".claude" / "skills" / source.name)
            for source in sorted(path for path in skill_root.iterdir() if path.is_dir())
        ]
        records.extend(
            artifact("file", home / ".claude" / "agents" / source.name)
            for source in sorted((REPO / "agents").glob("*.md"))
        )
        return records
    if group == "codex":
        return [
            artifact("file", home / ".codex" / "agents" / f"{source.stem}.toml")
            for source in sorted((REPO / "agents").glob("*.md"))
        ]
    if group == "pi":
        records = [
            artifact(
                "dir",
                home / ".pi" / "agent" / "extensions" / "agentic-engineering",
            )
        ]
        records.extend(
            artifact("file", home / ".pi" / "agent" / "agents" / source.name)
            for source in sorted((REPO / "agents").glob("*.md"))
        )
        return records
    if group == "hermes":
        root = hermes_skills_root(home)
        records = [
            artifact("dir", root / source.name) for source in hermes_skill_dirs()
        ]
        records.append(
            artifact("file", root / "agentic-engineering" / "SKILL.md")
        )
        return records
    raise ToolbeltError(f"unknown installation artifact group: {group}")


def detect_installed_providers(home: pathlib.Path) -> set[str]:
    installed: set[str] = set()
    if any(is_managed_dir(path) for path in (home / ".claude" / "skills").glob("*")):
        installed.add("claude")
    if any((home / ".codex" / "agents").glob(".*.agentic-engineering.json")):
        installed.add("codex")
    if is_managed_dir(home / ".pi" / "agent" / "extensions" / "agentic-engineering"):
        installed.add("pi")
    if any(is_managed_dir(path) for path in hermes_skills_root(home).glob("*")):
        installed.add("hermes")
    return installed


def load_install_state(home: pathlib.Path) -> dict[str, object]:
    path = install_state_path(home)
    if not path.is_file():
        return {
            "name": "agentic-engineering",
            "schemaVersion": 1,
            "providers": sorted(detect_installed_providers(home)),
            "artifacts": {},
        }
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ToolbeltError(f"invalid install state {path}: {exc}") from exc
    if not isinstance(state, dict) or state.get("name") != "agentic-engineering":
        raise ToolbeltError(f"invalid install state owner: {path}")
    if not isinstance(state.get("providers"), list) or not isinstance(state.get("artifacts"), dict):
        raise ToolbeltError(f"invalid install state shape: {path}")
    return state


def write_install_state(home: pathlib.Path, state: dict[str, object]) -> None:
    path = install_state_path(home)
    path.parent.mkdir(parents=True, exist_ok=True)
    if os.name != "nt":
        path.parent.chmod(0o700)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(state, handle, indent=2)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        if os.name != "nt":
            os.chmod(temp_name, 0o600)
        os.replace(temp_name, path)
    finally:
        pathlib.Path(temp_name).unlink(missing_ok=True)


def checked_artifact(record: object, home: pathlib.Path) -> tuple[str, pathlib.Path]:
    if not isinstance(record, dict) or record.get("kind") not in {"dir", "file"}:
        raise ToolbeltError("invalid artifact record in install state")
    raw = record.get("path")
    if not isinstance(raw, str):
        raise ToolbeltError("invalid artifact path in install state")
    path = pathlib.Path(os.path.abspath(os.path.expanduser(raw)))
    home_path = pathlib.Path(os.path.abspath(home.expanduser()))
    # The Hermes skills root may legitimately live outside the home root when
    # $HERMES_HOME points elsewhere (e.g. /data/hermes). Allow the live root AND
    # the root recorded in install state, so re-install/uninstall keep working
    # after $HERMES_HOME changes or is unset.
    allowed = [home_path, pathlib.Path(os.path.abspath(hermes_skills_root(home)))]
    try:
        recorded = load_install_state(home).get("hermesRoot")
    except ToolbeltError:
        recorded = None
    if isinstance(recorded, str):
        allowed.append(pathlib.Path(os.path.abspath(os.path.expanduser(recorded))))
    if not any(
        path == root or path.is_relative_to(root) for root in allowed
    ):
        raise ToolbeltError(f"install state artifact escapes home: {path}")
    return str(record["kind"]), path


def remove_artifact(record: object, home: pathlib.Path, *, dry_run: bool) -> None:
    kind, path = checked_artifact(record, home)
    if kind == "dir":
        remove_managed_dir(path, dry_run=dry_run)
    else:
        remove_managed_file(path, dry_run=dry_run)


def reconcile_artifacts(
    prior: object,
    desired: list[dict[str, str]],
    home: pathlib.Path,
    *,
    dry_run: bool,
) -> None:
    prior_records = prior if isinstance(prior, list) else []
    desired_keys = {(item["kind"], item["path"]) for item in desired}
    for record in prior_records:
        kind, path = checked_artifact(record, home)
        if (kind, str(path)) not in desired_keys:
            remove_artifact(record, home, dry_run=dry_run)


def preflight_managed_dir(destination: pathlib.Path, *, force: bool) -> None:
    """Verify a directory write would succeed, without mutating anything."""
    if (destination.exists() or destination.is_symlink()) and not force:
        require_pristine_managed_dir(destination)


def preflight_managed_file(path: pathlib.Path, *, force: bool) -> None:
    """Verify a file write would succeed, without mutating anything."""
    if path.exists() and not force:
        sidecar = managed_sidecar(path)
        if not sidecar.is_file():
            raise ToolbeltError(f"refusing to replace unmanaged file: {path}")
        try:
            prior = json.loads(sidecar.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ToolbeltError(f"invalid managed-file marker: {sidecar}") from exc
        if prior.get("sha256") != sha256(path):
            raise ToolbeltError(f"managed file was edited since installation: {path}")


def install_destinations(
    home: pathlib.Path, providers: tuple[str, ...]
) -> list[tuple[str, pathlib.Path]]:
    """(kind, path) for every destination an install of these providers writes.

    Mirrors the write order and conditions in install() so the whole selected
    artifact set can be preflighted before the first write.
    """
    destinations: list[tuple[str, pathlib.Path]] = [("file", launcher_path(home))]
    if "codex" in providers or "pi" in providers:
        destinations.extend(
            ("dir", home / ".agents" / "skills" / source.name) for source in skill_dirs()
        )
    if "claude" in providers:
        skill_root = REPO / "providers" / "claude" / "skills"
        destinations.extend(
            ("dir", home / ".claude" / "skills" / source.name)
            for source in sorted(path for path in skill_root.iterdir() if path.is_dir())
        )
        destinations.extend(
            ("file", home / ".claude" / "agents" / source.name)
            for source in sorted((REPO / "agents").glob("*.md"))
        )
    if "codex" in providers:
        for _source_path, content in generated_codex_agents().items():
            fields = re.search(r'^name = "([^"]+)"$', content, re.MULTILINE)
            if not fields:
                raise ToolbeltError("generated Codex agent has no name")
            destinations.append(("file", home / ".codex" / "agents" / f"{fields.group(1)}.toml"))
    if "pi" in providers:
        destinations.append(("dir", home / ".pi" / "agent" / "extensions" / "agentic-engineering"))
        destinations.extend(
            ("file", home / ".pi" / "agent" / "agents" / source.name)
            for source in sorted((REPO / "agents").glob("*.md"))
        )
    if "hermes" in providers:
        root = hermes_skills_root(home)
        destinations.extend(("dir", root / source.name) for source in hermes_skill_dirs())
        destinations.append(("file", root / "agentic-engineering" / "SKILL.md"))
    return destinations


def install(home: pathlib.Path, providers: tuple[str, ...], *, force: bool, dry_run: bool) -> None:
    errors = validate_source()
    if errors:
        raise ToolbeltError("source validation failed:\n- " + "\n- ".join(errors))

    state = load_install_state(home)
    installed = set(str(value) for value in state.get("providers", []))
    state_artifacts = state.get("artifacts", {})
    if not isinstance(state_artifacts, dict):
        raise ToolbeltError("invalid install state artifacts")

    # Preflight the entire selected artifact set before the first write, so an
    # unmanaged destination in one provider cannot leave earlier providers
    # half-installed with stale or absent state (mirrors uninstall's preflight).
    # Obsolete records (previously installed, no longer desired) are preflighted
    # too: an edited obsolete artifact must refuse before ANY write, not when
    # reconcile_artifacts reaches it after the launcher and current artifacts.
    desired_paths = {
        str(pathlib.Path(os.path.abspath(destination)))
        for _kind, destination in install_destinations(home, providers)
    }
    for provider in providers:
        prior = state_artifacts.get(provider)
        if isinstance(prior, list):
            for record in prior:
                if str(checked_artifact(record, home)[1]) not in desired_paths:
                    preflight_remove_artifact(record, home)
    if "codex" in providers or "pi" in providers:
        prior_shared = state_artifacts.get("shared")
        if isinstance(prior_shared, list):
            for record in prior_shared:
                if str(checked_artifact(record, home)[1]) not in desired_paths:
                    preflight_remove_artifact(record, home)
    for kind, destination in install_destinations(home, providers):
        if kind == "dir":
            preflight_managed_dir(destination, force=force)
        else:
            preflight_managed_file(destination, force=force)

    write_managed_file(
        launcher_path(home), launcher_content(), force=force, dry_run=dry_run, executable=True
    )

    if "codex" in providers or "pi" in providers:
        destination = home / ".agents" / "skills"
        for source in skill_dirs():
            copy_managed_dir(source, destination / source.name, force=force, dry_run=dry_run)
        shared = desired_artifacts(home, "shared")
        reconcile_artifacts(state_artifacts.get("shared"), shared, home, dry_run=dry_run)
        state_artifacts["shared"] = shared

    if "claude" in providers:
        claude_root = REPO / "providers" / "claude" / "skills"
        for source in sorted(path for path in claude_root.iterdir() if path.is_dir()):
            copy_managed_dir(
                source,
                home / ".claude" / "skills" / source.name,
                force=force,
                dry_run=dry_run,
            )
        for source in sorted((REPO / "agents").glob("*.md")):
            write_managed_file(
                home / ".claude" / "agents" / source.name,
                source.read_text(encoding="utf-8"),
                force=force,
                dry_run=dry_run,
            )
        claude = desired_artifacts(home, "claude")
        reconcile_artifacts(state_artifacts.get("claude"), claude, home, dry_run=dry_run)
        state_artifacts["claude"] = claude

    if "codex" in providers:
        for _source_path, content in generated_codex_agents().items():
            fields = re.search(r'^name = "([^"]+)"$', content, re.MULTILINE)
            if not fields:
                raise ToolbeltError("generated Codex agent has no name")
            write_managed_file(
                home / ".codex" / "agents" / f"{fields.group(1)}.toml",
                content,
                force=force,
                dry_run=dry_run,
            )
        codex = desired_artifacts(home, "codex")
        reconcile_artifacts(state_artifacts.get("codex"), codex, home, dry_run=dry_run)
        state_artifacts["codex"] = codex

    if "pi" in providers:
        copy_managed_dir(
            REPO / "providers" / "pi" / "extensions",
            home / ".pi" / "agent" / "extensions" / "agentic-engineering",
            force=force,
            dry_run=dry_run,
        )
        for source in sorted((REPO / "agents").glob("*.md")):
            write_managed_file(
                home / ".pi" / "agent" / "agents" / source.name,
                source.read_text(encoding="utf-8"),
                force=force,
                dry_run=dry_run,
            )
        pi = desired_artifacts(home, "pi")
        reconcile_artifacts(state_artifacts.get("pi"), pi, home, dry_run=dry_run)
        state_artifacts["pi"] = pi

    if "hermes" in providers:
        hermes_root = hermes_skills_root(home)
        for source in hermes_skill_dirs():
            if source.name == "execute":
                # The executor agent prompt rides inside the execute skill as a
                # linked reference so Hermes can load it with the skill; the
                # extra file is part of the managed snapshot.
                copy_managed_dir(
                    source,
                    hermes_root / source.name,
                    force=force,
                    dry_run=dry_run,
                    extra_files={
                        "references/executor.md": (REPO / "agents" / "executor.md").read_text(
                            encoding="utf-8"
                        )
                    },
                )
                continue
            copy_managed_dir(
                source,
                hermes_root / source.name,
                force=force,
                dry_run=dry_run,
            )
        # The router skill is the Hermes entry point (provider-specific, so it
        # ships from providers/hermes rather than the shared skills/). The
        # __TOOLBELT_REPO__ placeholder is rendered to the real checkout path so
        # the installed router can always resolve the excluded skills.
        router = (REPO / "providers" / "hermes" / "router.md").read_text(encoding="utf-8")
        router = router.replace("__TOOLBELT_REPO__", str(REPO))
        write_managed_file(
            hermes_root / "agentic-engineering" / "SKILL.md",
            router,
            force=force,
            dry_run=dry_run,
        )
        hermes = desired_artifacts(home, "hermes")
        reconcile_artifacts(state_artifacts.get("hermes"), hermes, home, dry_run=dry_run)
        state_artifacts["hermes"] = hermes

    if not dry_run:
        installed.update(providers)
        state["providers"] = sorted(installed)
        state["artifacts"] = state_artifacts
        if "hermes" in installed:
            # Persist the authorized Hermes skills root so reinstall/uninstall
            # still validate recorded artifacts after $HERMES_HOME changes or
            # is unset (the live env may no longer match the install-time root).
            state["hermesRoot"] = str(hermes_skills_root(home))
        write_install_state(home, state)
        print("install complete; start agents from the target application repository")


def remove_managed_dir(path: pathlib.Path, *, dry_run: bool) -> None:
    if not path.exists() and not path.is_symlink():
        return
    require_pristine_managed_dir(path)
    print(f"remove: {path}")
    if not dry_run:
        shutil.rmtree(path)


def remove_managed_file(path: pathlib.Path, *, dry_run: bool) -> None:
    sidecar = managed_sidecar(path)
    if not path.exists() and not sidecar.exists():
        return
    if not path.exists() or not sidecar.is_file():
        raise ToolbeltError(f"refusing partial/unmanaged removal: {path}")
    prior = json.loads(sidecar.read_text(encoding="utf-8"))
    if prior.get("sha256") != sha256(path):
        raise ToolbeltError(f"refusing to remove edited managed file: {path}")
    print(f"remove: {path}")
    if not dry_run:
        path.unlink()
        sidecar.unlink()


def preflight_remove_artifact(record: object, home: pathlib.Path) -> None:
    """Verify a removal would succeed, without mutating anything.

    Mirrors the checks inside remove_artifact/remove_managed_dir/
    remove_managed_file so a refusal surfaces before any deletion starts.
    """
    kind, path = checked_artifact(record, home)
    if kind == "dir":
        if path.exists() or path.is_symlink():
            require_pristine_managed_dir(path)
        return
    sidecar = managed_sidecar(path)
    if not path.exists() and not sidecar.exists():
        return
    if not path.exists() or not sidecar.is_file():
        raise ToolbeltError(f"refusing partial/unmanaged removal: {path}")
    prior = json.loads(sidecar.read_text(encoding="utf-8"))
    if prior.get("sha256") != sha256(path):
        raise ToolbeltError(f"refusing to remove edited managed file: {path}")


def uninstall(home: pathlib.Path, providers: tuple[str, ...], *, dry_run: bool) -> None:
    state = load_install_state(home)
    installed = set(str(value) for value in state.get("providers", []))
    state_artifacts = state.get("artifacts", {})
    if not isinstance(state_artifacts, dict):
        raise ToolbeltError("invalid install state artifacts")
    selected = set(providers)
    remaining = installed - selected
    # Only providers recorded as installed have artifacts to remove. Selecting a
    # provider that was never installed (e.g. hermes, after an upgrade added it
    # to PROVIDERS) must not fabricate desired artifacts and touch the user's
    # own directories.
    to_remove = sorted(selected & installed)

    records_by_provider: dict[str, list[dict[str, str]]] = {}
    for provider in to_remove:
        records = state_artifacts.get(provider)
        if not isinstance(records, list):
            records = desired_artifacts(home, provider)
        records_by_provider[provider] = records
    shared_records: list[dict[str, str]] = []
    if not ({"codex", "pi"} & remaining):
        shared = state_artifacts.get("shared")
        if not isinstance(shared, list):
            shared = desired_artifacts(home, "shared")
        shared_records = shared

    # Preflight the entire removal set before deleting anything, so a refusal on
    # one artifact cannot leave earlier providers half-removed while install
    # state still claims they exist.
    for records in records_by_provider.values():
        for record in records:
            preflight_remove_artifact(record, home)
    for record in shared_records:
        preflight_remove_artifact(record, home)
    if not remaining:
        preflight_remove_artifact(artifact("file", launcher_path(home)), home)

    for provider in to_remove:
        for record in records_by_provider[provider]:
            remove_artifact(record, home, dry_run=dry_run)
        state_artifacts.pop(provider, None)
    for record in shared_records:
        remove_artifact(record, home, dry_run=dry_run)
    if not ({"codex", "pi"} & remaining):
        state_artifacts.pop("shared", None)

    if not remaining:
        remove_managed_file(launcher_path(home), dry_run=dry_run)

    if not dry_run:
        state["providers"] = sorted(remaining)
        state["artifacts"] = state_artifacts
        if "hermes" not in remaining:
            state.pop("hermesRoot", None)
        if remaining:
            write_install_state(home, state)
        else:
            install_state_path(home).unlink(missing_ok=True)


def command_version(name: str) -> tuple[str, str]:
    executable = shutil.which(name)
    if not executable:
        return "missing", ""
    try:
        proc = subprocess.run(
            [executable, "--version"], capture_output=True, text=True, timeout=5, check=False
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return "error", str(exc)
    if proc.returncode != 0:
        return "error", f"exit {proc.returncode}"
    first = (proc.stdout or proc.stderr).strip().splitlines()
    return "available", first[0] if first else executable


def resolve_base(repo: pathlib.Path, *, github_branch: bool) -> str:
    """Resolve one authoritative review base, preferring remote-tracking refs."""
    repo = repo.resolve()

    def git(*args: str) -> subprocess.CompletedProcess[str]:
        try:
            return subprocess.run(
                ["git", "-C", str(repo), *args],
                capture_output=True,
                text=True,
                timeout=10,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise ToolbeltError(f"git {' '.join(args)} failed: {exc}") from exc

    symbolic = git("symbolic-ref", "--quiet", "--short", "refs/remotes/origin/HEAD")
    candidates: list[str] = []
    if symbolic.returncode == 0 and symbolic.stdout.strip():
        candidates.append(symbolic.stdout.strip())
    candidates.extend(("origin/main", "origin/master", "main", "master"))
    for candidate in dict.fromkeys(candidates):
        if git("rev-parse", "--verify", "--quiet", f"{candidate}^{{commit}}").returncode == 0:
            if github_branch:
                return candidate.removeprefix("refs/remotes/").removeprefix("origin/")
            return candidate
    raise ToolbeltError(
        "could not resolve a base ref from origin/HEAD, origin/main, origin/master, main, or master"
    )


